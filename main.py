#!/usr/bin/env python3
"""BROADSHEET — news-image-20261124. Stdlib only: copies the pre-rendered
entry.png (drawn by render.py and committed to the repo) to the output dir.
No rendering happens at runtime."""
import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def main():
    out_dir = os.environ.get("MAKEFUN_OUTPUT_DIR") or "/output"
    os.makedirs(out_dir, exist_ok=True)
    src = os.path.join(HERE, "entry.png")
    dst = os.path.join(out_dir, "entry.png")
    shutil.copyfile(src, dst)
    print("wrote", dst)
    return 0


if __name__ == "__main__":
    sys.exit(main())
